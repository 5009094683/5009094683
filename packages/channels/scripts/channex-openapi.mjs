// Builds the typed surface of the Channex API that the adapter uses.
//
//   pnpm --filter @pms/channels channex:types [path-or-url-of-the-full-spec]
//
// The published spec covers the whole product (about 1 MB). This keeps only
// the operations listed below, together with every schema they refer to, and
// generates TypeScript types from that subset. Both outputs are committed, so
// builds do not need network access and a spec change shows up as a diff.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const SOURCE = process.argv[2] ?? 'https://openapi.channex.io/public/openapi.json';
const here = dirname(fileURLToPath(import.meta.url));
const subsetFile = join(here, '..', 'src', 'channex', 'openapi.subset.json');
const typesFile = join(here, '..', 'src', 'channex', 'generated.ts');

/** path -> methods the adapter calls */
const OPERATIONS = {
  '/whoami': ['get'],
  '/properties': ['get', 'post'],
  '/properties/{id}': ['get'],
  '/room_types': ['get', 'post'],
  '/rate_plans': ['get', 'post'],
  '/availability': ['get', 'post'],
  '/restrictions': ['get', 'post'],
  '/booking_revisions/feed': ['get'],
  '/booking_revisions/{id}': ['get'],
  '/booking_revisions/{id}/ack': ['post'],
  '/bookings': ['get'],
  '/webhooks': ['get', 'post'],
  '/webhooks/{id}': ['put', 'delete'],
};

async function load(source) {
  if (/^https?:/.test(source)) {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`Could not download the spec: ${response.status}`);
    return response.json();
  }
  return JSON.parse(await readFile(source, 'utf8'));
}

function resolve(spec, ref) {
  return ref
    .slice(2)
    .split('/')
    .map((p) => p.replace(/~1/g, '/').replace(/~0/g, '~'))
    .reduce((node, key) => node?.[key], spec);
}

/** Collects every `#/components/...` reference reachable from `node`. */
function collect(spec, node, seen) {
  if (Array.isArray(node)) {
    for (const item of node) collect(spec, item, seen);
  } else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string' && value.startsWith('#/components/')) {
        if (!seen.has(value)) {
          seen.add(value);
          collect(spec, resolve(spec, value), seen);
        }
      } else {
        collect(spec, value, seen);
      }
    }
  }
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sortKeys(value[k])]),
    );
  }
  return value;
}

const spec = await load(SOURCE);
const paths = {};
for (const [path, methods] of Object.entries(OPERATIONS)) {
  const item = spec.paths[path];
  if (!item) throw new Error(`The spec no longer has ${path}`);
  paths[path] = {};
  if (item.parameters) paths[path].parameters = item.parameters;
  for (const method of methods) {
    if (!item[method]) throw new Error(`The spec no longer has ${method.toUpperCase()} ${path}`);
    paths[path][method] = item[method];
  }
}

const refs = new Set();
collect(spec, paths, refs);
const components = {};
for (const ref of refs) {
  const [, , section, name] = ref.split('/');
  const key = name.replace(/~1/g, '/').replace(/~0/g, '~');
  components[section] ??= {};
  components[section][key] = spec.components[section][key];
}
if (spec.components.securitySchemes) components.securitySchemes = spec.components.securitySchemes;

const subset = sortKeys({
  openapi: spec.openapi,
  info: { ...spec.info, description: 'Subset of the Channex public API used by the PMS.' },
  servers: spec.servers,
  security: spec.security,
  paths,
  components,
});
// Types keep the spec's descriptions as comments; the stored subset drops them to stay small.
function withoutProse(value) {
  if (Array.isArray(value)) return value.map(withoutProse);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .filter(
          ([k, v]) =>
            !((k === 'description' || k === 'summary') && typeof v === 'string') &&
            k !== 'example' &&
            k !== 'examples',
        )
        .map(([k, v]) => [k, withoutProse(v)]),
    );
  }
  return value;
}
await writeFile(subsetFile, `${JSON.stringify(withoutProse(subset), null, 1)}\n`);

const ast = await openapiTS(subset, { alphabetize: true });
const banner =
  '// Generated by scripts/channex-openapi.mjs from the Channex OpenAPI spec. Do not edit by hand.\n';
await writeFile(typesFile, banner + astToString(ast));

const operations = Object.values(OPERATIONS).reduce((n, m) => n + m.length, 0);
console.log(`Kept ${operations} operations and ${refs.size} components.`);
console.log(`Wrote ${subsetFile}`);
console.log(`Wrote ${typesFile}`);
